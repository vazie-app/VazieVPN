#!/usr/bin/env bash
# Writes Sources/VazieCore/TunScriptSource.swift from packaging/tun-run.sh. The app carries the root supervisor inside its
# signed executable instead of reading it from the bundle (where anyone who can write the bundle could change what runs as
# root), so this file and the script must agree; a test compares them.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=Sources/VazieCore/TunScriptSource.swift
{
  echo '// Generated by scripts/embed-tun-script.sh from packaging/tun-run.sh. Do not edit: change the script and run it again.'
  echo 'public enum TunScriptSource {'
  echo '    public static let text = #"""'
  cat packaging/tun-run.sh
  echo '"""#'
  echo '}'
} > "$OUT"
echo "wrote $OUT"
