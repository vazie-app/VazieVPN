// Split tunneling for a browser: which sites use the tunnel, in place of which apps. The three modes are the
// app's (`SplitTunnel.kt`): everything, everything except the listed sites, or only the listed sites.

export type SplitMode = "off" | "exclude" | "include";

export interface SplitTunnel {
  mode: SplitMode;
  sites: string[];
}

export const SPLIT_OFF: SplitTunnel = { mode: "off", sites: [] };

export const MAX_SITES = 500;
const MAX_SITE_LENGTH = 253;
const LABEL = /^(?!-)[a-z0-9-]{1,63}(?<!-)$/;

export function modeFromId(id: unknown): SplitMode {
  return id === "exclude" || id === "include" ? id : "off";
}

/** Whether anything is actually split: a mode with no sites chosen changes nothing. */
export function isActive(split: SplitTunnel): boolean {
  return split.mode !== "off" && split.sites.length > 0;
}

/** A site as it is stored — a bare lowercase host that also stands for its subdomains — from whatever a person
 * typed or pasted: an address, `*.example.com`, a host with a port. `null` when it is none of those. */
export function normalizeSite(input: string): string | null {
  let text = input.trim().toLowerCase();
  if (text === "") return null;
  if (text.includes("://")) {
    try {
      text = new URL(text).hostname;
    } catch {
      return null;
    }
  } else {
    text = text.split(/[/?#]/, 1)[0] as string;
    // `host:port` and `[::1]:80`; a bare IPv6 literal has no port to cut.
    if (!text.startsWith("[") && text.split(":").length === 2) text = text.split(":")[0] as string;
  }
  text = text.replace(/^\*\./, "").replace(/^\./, "").replace(/\.$/, "");
  if (text === "" || text.length > MAX_SITE_LENGTH) return null;
  if (text.startsWith("[") && text.endsWith("]")) return /^\[[0-9a-f:.]+\]$/.test(text) ? text : null;
  if (/^[0-9.]+$/.test(text)) return isIpv4(text) ? text : null;
  const labels = text.split(".");
  if (labels.length < 1 || !labels.every((label) => LABEL.test(label))) return null;
  return text;
}

function isIpv4(text: string): boolean {
  const parts = text.split(".");
  return parts.length === 4 && parts.every((p) => /^[0-9]{1,3}$/.test(p) && Number(p) <= 255);
}

/** The host of a tab's address, as a stored site; `null` for pages that have none (`chrome://`, a new tab). */
export function siteOfUrl(url: string | undefined): string | null {
  if (!url) return null;
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "http:" && parsed.protocol !== "https:") return null;
    return normalizeSite(parsed.hostname);
  } catch {
    return null;
  }
}

export function addSite(split: SplitTunnel, input: string): SplitTunnel | null {
  const site = normalizeSite(input);
  if (site === null) return null;
  if (split.sites.includes(site)) return split;
  if (split.sites.length >= MAX_SITES) return null;
  return { ...split, sites: [...split.sites, site].sort() };
}

export function removeSite(split: SplitTunnel, site: string): SplitTunnel {
  return { ...split, sites: split.sites.filter((s) => s !== site) };
}

/** Sites that are never sent to the tunnel server: it cannot reach a person's own machine or network. */
const LOCAL_SUFFIXES = [".local", ".localhost", ".lan", ".home.arpa", ".internal"];

/** The proxy auto-config the browser runs for every request. It fails closed: a request meant for the tunnel
 * is answered with the tunnel's address alone, never with a fallback to `DIRECT`. */
export function pacScript(split: SplitTunnel, proxyPort: number): string {
  const sites = isActive(split) ? split.sites : [];
  const mode = isActive(split) ? split.mode : "off";
  return `// Generated by Vazie VPN. Do not edit.
var PROXY = "PROXY 127.0.0.1:${proxyPort}";
var MODE = ${JSON.stringify(mode)};
var SITES = ${JSON.stringify(sites)};
var LOCAL_SUFFIXES = ${JSON.stringify(LOCAL_SUFFIXES)};

function isLocal(host) {
  if (host === "localhost" || (host.indexOf(".") < 0 && host.indexOf(":") < 0)) return true;
  for (var i = 0; i < LOCAL_SUFFIXES.length; i++) {
    var s = LOCAL_SUFFIXES[i];
    if (host.length > s.length && host.slice(-s.length) === s) return true;
  }
  var m = /^(\\d+)\\.(\\d+)\\.(\\d+)\\.(\\d+)$/.exec(host);
  if (m) {
    var a = +m[1], b = +m[2];
    return a === 10 || a === 127 || a === 0 || (a === 169 && b === 254) ||
      (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168) || (a === 100 && b >= 64 && b <= 127);
  }
  if (host.charAt(0) === "[" || host.indexOf(":") >= 0) {
    var h = host.replace(/^\\[|\\]$/g, "").toLowerCase();
    return h === "::1" || h === "::" || /^f[cd]/.test(h) || /^fe[89ab]/.test(h);
  }
  return false;
}

function listed(host) {
  for (var i = 0; i < SITES.length; i++) {
    var s = SITES[i];
    if (host === s || (host.length > s.length && host.slice(-s.length - 1) === "." + s)) return true;
  }
  return false;
}

function FindProxyForURL(url, host) {
  host = host.toLowerCase();
  if (isLocal(host)) return "DIRECT";
  if (MODE === "exclude") return listed(host) ? "DIRECT" : PROXY;
  if (MODE === "include") return listed(host) ? PROXY : "DIRECT";
  return PROXY;
}
`;
}

/** The same decision in TypeScript, for the tests and for the popup's "this site" row. */
export function routesThroughTunnel(split: SplitTunnel, host: string): boolean {
  const h = host.toLowerCase();
  const listed = split.sites.some((s) => h === s || h.endsWith("." + s));
  if (!isActive(split)) return true;
  return split.mode === "exclude" ? !listed : listed;
}
